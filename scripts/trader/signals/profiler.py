"""Daily Profiler signal — replicates the PineScript auto-filter logic.

**Canonical data flow (v1.3.0+):**
  1. **Live sessions** come from ``SessionBoxEngine.from_live(ticker)`` which
     reads the live 1m parquet and classifies the current session box statuses
     (status + broken) for today.
  2. **Historical predictions** come from the **precomputed lookup table** at
     ``data/derived/{ticker}_profiler_lookup.json`` (generated by
     ``scripts/libs_py/profiler/generate_profiler_lookup.py``). The lookup
     table is keyed by context signature (status|broken|...) and contains
     per-outcome probabilities, price stats, HOD/LOD timing, broken rates,
     and per-outcome level hit rates.
  3. ``compute_profiler()`` joins the two: live sessions provide the filter
     signature, the lookup table provides the historical conditional
     statistics. No raw ``{ticker}_profiler.json`` filtering is needed at
     runtime — that file is an input to the lookup table generator, not a
     runtime data source.

The module replicates the exact filtering logic from the PineScript indicator
(`ProfilerIndicator.pine`):

1. **Auto-detect target session** — which session are we predicting next?
   Based on which sessions have completed their play windows.

2. **Build filter signature** from resolved sessions — using the Context
   Dependency Chain from PROFILER_ARCHITECTURE.md:
     Asia  → prev NY1 + prev NY2
     London → curr Asia + prev NY2
     NY1   → curr Asia + curr London
     NY2   → curr Asia + curr London + curr NY1

3. **Lookup predictions** by context key with hierarchical fallback
   (S3 architecture): if full context has < 30 samples, drop context
   dimensions one at a time; if still insufficient, fall back to base rates.

Session definitions (ET, from PROFILER_REQUIREMENTS.md):
  Classification windows (where the box H/L is set):
    Asia    18:00-19:29
    London  02:30-03:29
    NY1     07:30-08:29
    NY2     11:30-12:29
  Full session windows (where status is determined):
    Asia    19:30-02:29
    London  03:30-07:29
    NY1     08:30-11:29
    NY2     12:30-15:59
  Broken windows:
    Asia    02:30-17:00
    London  07:30-17:00
    NY1     11:30-17:00
    NY2     16:00-17:00

Status codes (numeric, from PineScript):
  0 = Neutral (not started)
  1 = Long True (PENDING — can still flip to 2)
  2 = Long False (FINAL)
  3 = Short True (PENDING — can still flip to 4)
  4 = Short False (FINAL)

Data files:
  Runtime (lookup table):
  - ``data/derived/{ticker}_profiler_lookup.json`` — context-keyed predictions,
    per-outcome level hit rates, base rates. Generated by
    ``generate_profiler_lookup.py``.
  - ``data/{ticker}_level_touches.json`` — per-day level touch data (used for
    today's reference levels + P12 scenario only).
  Generation inputs (not read at runtime):
  - ``data/{ticker}_profiler.json`` — session records (input to lookup generator)
  - ``data/{ticker}_daily_hod_lod.json`` — daily HOD/LOD (input to lookup generator)
  - ``data/{ticker}_level_touches_columnar.json`` — columnar hits (input to lookup generator)
"""
